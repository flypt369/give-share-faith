export function translate(key: string, lang: LanguageCode, replacements?: Record<string, string>): string {
  const translationKey = key as keyof typeof translations.en;
  let text = translations[lang][translationKey] || translations.en[translationKey] || key;

  if (replacements) {
    Object.entries(replacements).forEach(([placeholder, value]) => {
      text = text.replace(`{{${placeholder}}}`, value);
    });
  }

  return text;
}
